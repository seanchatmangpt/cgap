#[test]
fn kat_keygen_acvp() {
    // keyGen tcId 26 and 27 (ML-KEM-768): d,z -> byte-exact ek,dk.
    let d = uh32(KG1_D);
    let z = uh32(KG1_Z);
    let mut ek = [0u8; 1184];
    let mut dk = [0u8; 2400];
    kem::keygen(&d, &z, &mut ek, &mut dk);
    assert_eq!(&hx(&ek), KG1_EK, "ACVP keyGen tcId 26 ek");
    assert_eq!(&hx(&dk), KG1_DK, "ACVP keyGen tcId 26 dk");
    let d2 = uh32(KG2_D);
    let z2 = uh32(KG2_Z);
    let mut ek2 = [0u8; 1184];
    let mut dk2 = [0u8; 2400];
    kem::keygen(&d2, &z2, &mut ek2, &mut dk2);
    assert_eq!(&hx(&ek2), KG2_EK, "ACVP keyGen tcId 27 ek");
    assert_eq!(&hx(&dk2), KG2_DK, "ACVP keyGen tcId 27 dk");
}

#[test]
fn kat_encaps_acvp() {
    // encapsulation tcId 26 and 27: ek,m -> byte-exact ct,ss.
    let ek: [u8; 1184] = uh_slice(EN1_EK).try_into().unwrap();
    let m = uh32(EN1_M);
    let mut ct = [0u8; 1088];
    let mut ss = [0u8; 32];
    kem::encaps(&ek, &m, &mut ct, &mut ss);
    assert_eq!(&hx(&ct), EN1_C, "ACVP encaps tcId 26 ct");
    assert_eq!(&hx(&ss), EN1_K, "ACVP encaps tcId 26 ss");
    let ek2: [u8; 1184] = uh_slice(EN2_EK).try_into().unwrap();
    let m2 = uh32(EN2_M);
    let mut ct2 = [0u8; 1088];
    let mut ss2 = [0u8; 32];
    kem::encaps(&ek2, &m2, &mut ct2, &mut ss2);
    assert_eq!(&hx(&ct2), EN2_C, "ACVP encaps tcId 27 ct");
    assert_eq!(&hx(&ss2), EN2_K, "ACVP encaps tcId 27 ss");
}

