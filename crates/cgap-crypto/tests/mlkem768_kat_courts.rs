#[test]
fn kat_implicit_rejection_acvp() {
    // FIPS 203 §7.3: one flipped ciphertext byte -> decaps is INFALLIBLE
    // and returns the deterministic rejection pseudosecret J(z || ct'),
    // never the true ss. Deterministic: same corrupted ct decaps to the
    // same pseudosecret twice.
    let dk: [u8; 2400] = uh_slice(DE1_DK).try_into().unwrap();
    let ct: [u8; 1088] = uh_slice(DE1_C).try_into().unwrap();
    let ss_true = kem::decaps(&dk, &ct);
    assert_eq!(&hx(&ss_true), DE1_K, "honest ct decaps to the ACVP ss");
    for pos in [0usize, 543, 1087] {
        let mut bad = ct;
        bad[pos] ^= 0x01;
        let rej = kem::decaps(&dk, &bad);
        assert_ne!(rej, ss_true, "implicit rejection at byte {pos}");
        let rej2 = kem::decaps(&dk, &bad);
        assert_eq!(rej, rej2, "rejection pseudosecret deterministic at byte {pos}");
    }
}
