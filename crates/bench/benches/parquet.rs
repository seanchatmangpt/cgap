//! Lane F2-12 BENCH-PARQUET — v26.11.1 wave F2, item 12.
//!
//! Three measurement groups over the cgap-parquet membrane:
//!
//! (1) `bit_unpack` — SWAR bit-unpack kernel set at the spec-pinned widths
//!     {1, 2, 4, 8} over 65_536-lane corpora. Widths outside the kernel set
//!     are refused by design (`ParquetError::UnsupportedBitWidth`) and are
//!     deliberately NOT benched — no off-spec width reaches a kernel here.
//! (2) `rle_decode_direct` — `rle::decode_into` writes lanes straight into
//!     caller-owned memory. THE ALLOC COLUMN IS THE VERDICT: Divan's
//!     allocation counter must read 0 B on this row.
//! (3) `rle_decode_staged` — the DOE-2 arm: a bench-local staged wrapper
//!     (decode into an intermediate `Vec`, then copy out) so the table shows
//!     direct vs staged side by side. The kernel (`rle.rs`) is untouched —
//!     spec M-3 kernel purity; staging lives only in this file.
//!
//! Corpus law: every corpus is generated by canonical SplitMix64, seeded
//! 0xBF58_476D_1CE4_E5B9 (verbatim). Setup gates assert each benched path
//! against an independent in-file scalar reference before timing, and the
//! post-run state is checksum-asserted. A gate failure panics loud — never
//! a silent bench of garbage.

use std::sync::Mutex;

use cgap_parquet::rle::{decode_into, rle_encode};
use cgap_parquet::unpack::unpack_bits;
use divan::{black_box, Bencher};

/// Divan allocation counting (the alloc column is the verdict for the RLE
/// decode rows). Divan's own `#[global_allocator]` is `#[cfg(test)]`-only, so
/// the bench binary must install `AllocProfiler` itself — documented pattern
/// (divan 0.1.21 src/alloc.rs). Without this, tallies are never collected
/// and any 0 B claim would be vacuous.
#[global_allocator]
static ALLOC: divan::AllocProfiler = divan::AllocProfiler::system();

/// 65_536 lanes per corpus (spec-pinned corpus size).
const LANES: usize = 1 << 16;

/// Canonical SplitMix64 seed, verbatim per lane spec.
const SEED: u64 = 0xBF58_476D_1CE4_E5B9;

/// Canonical SplitMix64 — deterministic corpus source.
struct SplitMix64 {
    state: u64,
}

impl SplitMix64 {
    fn new(seed: u64) -> Self {
        Self { state: seed }
    }

    fn next_u64(&mut self) -> u64 {
        self.state = self.state.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = self.state;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }
}

/// FNV-1a 64 checksum over `u32` lanes (word-wise FNV variant).
fn fnv_u32(lanes: &[u32]) -> u64 {
    let mut h: u64 = 0xCBF2_9CE4_8422_2325;
    for &v in lanes {
        h ^= u64::from(v);
        h = h.wrapping_mul(0x100_0000_01B3);
    }
    h
}

/// FNV-1a 64 checksum over `u64` lanes (word-wise FNV variant).
fn fnv_u64(lanes: &[u64]) -> u64 {
    let mut h: u64 = 0xCBF2_9CE4_8422_2325;
    for &v in lanes {
        h ^= v;
        h = h.wrapping_mul(0x100_0000_01B3);
    }
    h
}

// ------------------------------------------------------------------
// (1) SWAR bit-unpack kernel set, widths {1, 2, 4, 8}
// ------------------------------------------------------------------

/// Packed corpus: LANES lanes at `bits` bits per lane, SplitMix64-filled.
fn packed_corpus(bits: u8) -> Vec<u64> {
    let words = LANES * usize::from(bits) / 64;
    let mut rng = SplitMix64::new(SEED ^ (u64::from(bits) << 56));
    (0..words).map(|_| rng.next_u64()).collect()
}

/// Independent scalar reference: lane `i` lives in word `i*bits/64` at bit
/// offset `(i*bits) % 64`. Every kernel-set width divides 64, so lanes never
/// straddle word boundaries and the reference reads one word per lane.
fn ref_unpack(bits: u8, src: &[u64]) -> Vec<u64> {
    let bits_us = usize::from(bits);
    let mask = (1u64 << bits) - 1;
    (0..LANES)
        .map(|i| (src[(i * bits_us) / 64] >> ((i * bits_us) % 64)) & mask)
        .collect()
}

#[divan::bench(args = [1u8, 2, 4, 8])]
fn bit_unpack(b: Bencher, bits: u8) {
    let src = packed_corpus(bits);
    let mut out = vec![0u64; LANES];

    // Setup gate: kernel output must equal the independent reference.
    unpack_bits(bits, &src, &mut out).expect("kernel set width must decode");
    let want = ref_unpack(bits, &src);
    assert_eq!(out, want, "kernel vs reference mismatch at width {bits}");
    let want_sum = fnv_u64(&out);

    // Mutex because divan's Bencher closure is Fn (Send-bound); uncontended
    // per-bench lock on real state, matching the v26_10_31.rs pattern.
    let out = Mutex::new(out);
    b.bench(|| {
        let mut out = out.lock().unwrap();
        unpack_bits(bits, black_box(&src), black_box(&mut out)).expect("unpack_bits");
    });

    // Final-state checksum assert: last iteration's buffer is unchanged law.
    let out = out.into_inner().unwrap();
    assert_eq!(
        fnv_u64(&out),
        want_sum,
        "bit_unpack checksum drifted at width {bits}"
    );
}

// ------------------------------------------------------------------
// (2)+(3) RLE decode: direct-into-caller vs DOE-2 staged arm
// ------------------------------------------------------------------

/// Mixed literal+run corpus, width 8: a SplitMix64 run of 3..=10 lanes every
/// 64-lane stretch, literals elsewhere — exercises BOTH decoder arms
/// (repeated runs and literal groups). `shape` varies the stream, not the
/// statistics; the direct and staged arms share one corpus.
fn rle_corpus(shape: u64) -> (Vec<u32>, Vec<u8>) {
    let mut rng = SplitMix64::new(SEED ^ shape);
    let mut values = Vec::with_capacity(LANES);
    let mut i = 0;
    while i < LANES {
        if i % 64 == 0 {
            let run = 3 + (rng.next_u64() % 8) as usize;
            let v = (rng.next_u64() & 0xFF) as u32;
            let run = run.min(LANES - i);
            for _ in 0..run {
                values.push(v);
            }
            i += run;
        } else {
            values.push((rng.next_u64() & 0xFF) as u32);
            i += 1;
        }
    }
    let page = rle_encode(&values, 8);
    (values, page)
}

/// (2) Direct-into-caller decode — THE ALLOC COLUMN IS THE VERDICT.
/// `decode_into` writes lanes into the pre-allocated caller buffer; Divan's
/// allocation counter must read 0 B on this row.
#[divan::bench]
fn rle_decode_direct(b: Bencher) {
    let (values, page) = rle_corpus(0x0D1E_C0DE_0001);
    assert_eq!(values.len(), LANES);
    let mut out = vec![0u32; LANES];

    // Setup gates: exact full-buffer decode, exact equality, checksum pin.
    let n = decode_into(black_box(&page), &mut out).expect("decode_into");
    assert_eq!(n, LANES, "page must exactly fill the caller buffer");
    assert_eq!(out, values, "direct decode mismatch vs corpus");
    let want_sum = fnv_u32(&out);

    let out = Mutex::new(out);
    b.bench(|| {
        let mut out = out.lock().unwrap();
        decode_into(black_box(&page), black_box(&mut out)).expect("decode_into");
    });

    let out = out.into_inner().unwrap();
    assert_eq!(
        fnv_u32(&out),
        want_sum,
        "rle_decode_direct checksum drifted"
    );
}

/// (3) DOE-2 staged arm — bench-local wrapper ONLY (M-3 kernel purity: the
/// kernel `rle.rs` is untouched). Decode into an intermediate `Vec`, then
/// copy into the caller's buffer. This row doubles as the alloc-counter
/// POSITIVE CONTROL: it must show > 0 B allocated, or the 0 B verdict on
/// `rle_decode_direct` is vacuous and the whole table is a VACUOUS GATE.
fn staged_decode(src: &[u8], lanes: usize) -> Vec<u32> {
    let mut tmp = vec![0u32; lanes];
    decode_into(src, &mut tmp).expect("staged decode");
    tmp
}

#[divan::bench]
fn rle_decode_staged(b: Bencher) {
    // Same corpus as the direct arm — the contrast is the staging, not data.
    let (values, page) = rle_corpus(0x0D1E_C0DE_0001);
    let out = vec![0u32; LANES];

    // Setup gates: staged output equals corpus and equals the direct path.
    let staged = staged_decode(&page, LANES);
    assert_eq!(staged, values, "staged decode mismatch vs corpus");
    let mut direct = vec![0u32; LANES];
    decode_into(&page, &mut direct).expect("direct setup decode");
    assert_eq!(
        staged, direct,
        "staged vs direct mismatch (DOE-2 arms differ)"
    );
    let want_sum = fnv_u32(&staged);

    let out = Mutex::new(out);
    b.bench(|| {
        let mut out = out.lock().unwrap();
        let staged = staged_decode(black_box(&page), LANES);
        out.copy_from_slice(&staged);
    });

    let out = out.into_inner().unwrap();
    assert_eq!(
        fnv_u32(&out),
        want_sum,
        "rle_decode_staged checksum drifted"
    );
}

